# ============================================================
#  第 1 课：Python 对象的"三要素"
# ============================================================
#
# 前面学 import / 字节码时，我们已经建立了一个核心模型：
#     「Python 的变量 = 名字；名字通过绑定指向对象」
#
# 那么被指向的"对象"本身是什么？这是本课要回答的问题。
#
# Python 有一句金句：Everything is an object（一切皆对象）
#   数字、字符串、列表、函数、类、模块、甚至"类型"本身，都是对象。
#
# 每个对象都有三个不可分离的属性 —— 称为"对象三要素"：
#   1. 身份 (identity) —— id()   查看，对象生命周期内唯一不变
#   2. 类型 (type)     —— type() 查看，决定对象"能做什么"，也终身不变
#   3. 值   (value)    —— 对象承载的数据/状态，"可能"会变（视类型而定）
#
# 本课用代码逐个验证这三点。
# ============================================================


# ---------- 1. 身份 (identity)：每个对象的"身份证号" ----------
# 注意 b 用 int("1000") 而不是直接写 1000：
#   如果写 b = 1000，CPython 编译时会做"常量折叠"，把两个 1000 复用成同一个对象，
#   那样 a is b 就会诡异地是 True，掩盖了我们想演示的"两个独立对象"。
#   用 int("1000") 强制在运行时新建一个对象，才能看到真正的"值相等但身份不同"。
a = 1000
b = int("1000")   # 值与 a 相等，但是另一个独立对象
print('=== 1. 身份 id() ===')
print(f'a 的 id : {id(a)}')
print(f'b 的 id : {id(b)}')
print(f'a is b  : {a is b}        ← False：两个名字指向两个不同的对象')
print(f'a == b  : {a == b}        ← True ：但它们的值相等')
print()
# 小知识：在 CPython 里，id() 返回的就是对象在内存里的地址（一个整数）
#         可以把它理解成对象在内存中的"门牌号"
# 顺带记住一个坑：模块顶层写两次相同的字面量（如 a=1000; b=1000），
#         CPython 会做常量折叠让它们共享同一个对象——所以判断"是不是同一对象"
#         最可靠的方式是用 int(...)、list(...) 等运行时构造，而不是字面量。


# ---------- 2. 类型 (type)：决定对象"能做什么" ----------
print('=== 2. 类型 type() ===')
print(f'type(a)       = {type(a)}')            # <class 'int'>
print(f'type("hello") = {type("hello")}')      # <class 'str'>
print(f'type([1,2])   = {type([1,2])}')        # <class 'list'>
print(f'type(print)   = {type(print)}')        # <class 'builtin_function_or_method'>
print(f'type(int)     = {type(int)}')          # <class 'type'>  ← 类型本身也是对象！
print()

# 类型决定了对象支持哪些操作。可以用 dir() 问一个类型/对象："你能干啥？"
int_abilities = [x for x in dir(int) if not x.startswith('_')]
print(f'int 能做的事（部分）: {int_abilities[:8]}')
print('  ↑ 这些都是 int 类型承诺给它的对象的能力，比如 .bit_length() .real 等')
print()


# ---------- 3. 值 (value)：对象承载的状态 ----------
print('=== 3. 值（状态） ===')
print(f'a 的值: {a}')
print()

# 关键问题：对象的"值"会不会变？
# 这是下一课的核心——"可变 (mutable) vs 不可变 (immutable)"
# 这里先剧透一眼，让你有直观印象：

n = 10
lst = [1, 2, 3]

print('--- 数字（不可变）---')
print(f'改之前 n 的 id : {id(n)}')
n = n + 1                       # 看上去 n "变了"
print(f'改之后 n 的 id : {id(n)}   ← id 变了！其实是新建了对象，名字 n 重新指向了它')
print()

print('--- 列表（可变）---')
print(f'改之前 lst 的 id : {id(lst)}')
lst.append(4)                   # list 本身被原地修改
print(f'改之后 lst 的 id : {id(lst)}   ← id 没变！同一个对象，内部状态被改了')
print(f'lst 现在的值: {lst}')
print()


